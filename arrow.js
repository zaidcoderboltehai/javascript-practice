// 3. Arrow Function (ES6)  
// Modern aur short syntax se function define karte hain

const add = (a, b) => a + b;  
// ‘add’ naam ka constant arrow function hai  
// (a, b) parameters hain  
// => ke baad wala expression (a + b) automatically return hota hai

console.log(add(2, 3));  
// yahan function call kar rahe hain with arguments 2 aur 3  
// console pe 5 print hoga  
