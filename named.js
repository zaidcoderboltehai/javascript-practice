// 1. Named Function (Declaration)
function sayHello() {                
  // Function define kar rahe hain, naam hai sayHello

  console.log("Hello!");             
  // Jab function chalega, yeh line console pe “Hello!” print karegi

}                                     
// Function definition yahin khatam hoti hai

sayHello();                           
// Function ko call kar rahe hain – is se upar wala code run hoga aur console pe “Hello!” aayega 
